// Command fakelimen runs the provider's in-memory stand-in for Limen, to try
// the provider locally without a control plane:
//
//	go run ./tools/fakelimen -dir .fakelimen
//	source .fakelimen/env.sh
//
// It writes the CA, a person's certificate (alice, limen:admin), and env.sh,
// and serves a fake GitHub Actions token service, so the bot login path works
// too. It seeds the resource profile `payments-postgres` and the bot
// `payments-terraform`, whose grant covers `payments-*` in namespace
// `payments`. Role mappings written by the bot are held for approval;
// approve them with `-approve`.
//
// It is not Limen. Anything checked only against it is unverified against a
// real control plane.
package main

import (
	"flag"
	"fmt"
	"log"
	"net"
	"net/http"
	"os"
	"os/signal"
	"path/filepath"
	"sync/atomic"
	"time"

	"github.com/limen-dev/terraform-provider-limen/internal/fakelimen"
	managev1 "github.com/limen-dev/terraform-provider-limen/internal/limenpb/limen/manage/v1"
)

func main() {
	dir := flag.String("dir", ".fakelimen", "where to write the CA, alice's certificate, and env.sh")
	addr := flag.String("listen", "127.0.0.1:7443", "the fake proxy's address")
	ghAddr := flag.String("github-listen", "127.0.0.1:7444", "the fake GitHub Actions token service's address")
	approveAfter := flag.Duration("approve", 0, "approve held changes this long after they are made (0: never)")
	flag.Parse()

	srv, err := fakelimen.Start(fakelimen.Options{Address: *addr})
	if err != nil {
		log.Fatal(err)
	}
	// Not deferred: log.Fatal below exits without running defers, and
	// Ctrl-C ends the process anyway.
	srv.AddAdmin("alice")
	srv.AddWriter("payments-terraform", fakelimen.Writer{
		Name: "payments-terraform", Namespace: "payments", NamePatterns: []string{"payments-*"},
		Kinds: []managev1.DocumentKind{
			managev1.DocumentKind_DOCUMENT_KIND_RESOURCE, managev1.DocumentKind_DOCUMENT_KIND_ROLE,
			managev1.DocumentKind_DOCUMENT_KIND_ROLE_MAPPING, managev1.DocumentKind_DOCUMENT_KIND_POLICY_TEST,
		},
		Profiles: []string{"payments-postgres"}, MaxDocuments: 200, ApproverGroups: []string{"security"},
	})
	srv.HoldWritesTo(managev1.DocumentKind_DOCUMENT_KIND_ROLE_MAPPING)
	if err := srv.Seed(&managev1.Document{
		Kind: managev1.DocumentKind_DOCUMENT_KIND_RESOURCE_PROFILE, Name: "payments-postgres",
		Description: "Payments' RDS PostgreSQL databases in eu-west-1",
		SpecJson: `{"template":{"postgres":{"iam_auth":true,"region":"eu-west-1","tls_ca_file":"/etc/limen/rds-ca.pem"},"worker_selector":{"network":"payments-vpc"}},
			"settable":{"postgres.endpoint":{"hosts":["*.c9xk2p.eu-west-1.rds.amazonaws.com"],"ports":[5432]},"postgres.default_database":{}},
			"labels":{"fixed":{"team":"payments"},"allowed":{"env":["dev","staging"]}}}`,
	}, nil); err != nil {
		log.Fatal(err)
	}

	var minted atomic.Int64
	ghLis, err := net.Listen("tcp", *ghAddr)
	if err != nil {
		log.Fatal(err)
	}
	gh := &http.Server{ReadHeaderTimeout: 5 * time.Second, Handler: http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		tok := fmt.Sprintf("gh-%d", minted.Add(1))
		srv.AddBotToken(tok, "github_actions", "payments-terraform")
		_, _ = fmt.Fprintf(w, `{"value":%q}`, tok)
	})}
	go func() { _ = gh.Serve(ghLis) }()

	cert, key, err := srv.IssueCertificate("alice", 12*time.Hour)
	if err != nil {
		log.Fatal(err)
	}
	abs, err := filepath.Abs(*dir)
	if err != nil {
		log.Fatal(err)
	}
	must(os.MkdirAll(abs, 0o700))
	must(os.WriteFile(filepath.Join(abs, "ca.pem"), []byte(srv.CAPEM), 0o600))
	must(os.WriteFile(filepath.Join(abs, "alice.pem"), []byte(cert), 0o600))
	must(os.WriteFile(filepath.Join(abs, "alice-key.pem"), []byte(key), 0o600))
	env := fmt.Sprintf(`# Generated by fakelimen. Source it in the shell you run terraform or tofu from.
export LIMEN_ADDRESS=%s
export LIMEN_CA_FILE=%s
# As the payments bot, through a fake GitHub Actions token service:
export LIMEN_BOT_METHOD=github_actions
export ACTIONS_ID_TOKEN_REQUEST_URL=http://%s/token
export ACTIONS_ID_TOKEN_REQUEST_TOKEN=fake
# As alice (limen:admin) instead: unset LIMEN_BOT_METHOD and set the provider's
# client_certificate to file("%s") and file("%s").
`, srv.Address, filepath.Join(abs, "ca.pem"), ghLis.Addr(), filepath.Join(abs, "alice.pem"), filepath.Join(abs, "alice-key.pem"))
	must(os.WriteFile(filepath.Join(abs, "env.sh"), []byte(env), 0o600))
	log.Printf("fake Limen on %s; wrote %s/env.sh", srv.Address, abs)

	if *approveAfter > 0 {
		go func() {
			scheduled := map[string]bool{}
			for range time.Tick(time.Second) {
				for _, id := range srv.PendingChanges() {
					if scheduled[id] {
						continue
					}
					scheduled[id] = true
					go func(id string) {
						time.Sleep(*approveAfter)
						if srv.Decide(id, true, "carol", "approved by fakelimen") == nil {
							log.Printf("approved %s", id)
						}
					}(id)
				}
			}
		}()
	}
	stop := make(chan os.Signal, 1)
	signal.Notify(stop, os.Interrupt)
	<-stop
	srv.Close()
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
